create or replace function public.bible_prompt_copy(p_user uuid,p_receipt uuid,p_key text,p_locale text,p_text text,p_expected_cost integer default 5)
returns jsonb language plpgsql security invoker set search_path='' as $$
declare total bigint; receipt public.bible_expression_copy_receipts%rowtype; v_owner boolean;
begin
 if p_user is null then raise exception 'Sign in first' using errcode='42501'; end if;
 if p_receipt is null or p_key is null or not exists(select 1 from aipoger_private.bible_prompt_keys where prompt_key=p_key)
  or p_locale is null or p_locale not in ('zh','en') or p_text is null or length(p_text) not between 1 and 8000 then
  raise exception 'Invalid copy' using errcode='22023';
 end if;
 perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended(p_user::text,0));
 select * into receipt from public.bible_expression_copy_receipts where user_id=p_user and source_id=p_receipt;
 select coalesce(sum(delta),0) into total from public.creator_credit_history where user_id=p_user;
 if receipt.id is not null then
  if receipt.prompt_key<>p_key or receipt.copy_locale<>p_locale then return jsonb_build_object('error','COPY_CONFLICT'); end if;
  return jsonb_build_object('charged',0,'balance',greatest(total,0),'debt',greatest(-total,0),'text',receipt.copy_text,'exempt',receipt.reason='owner_prompt_copy');
 end if;
 -- Reuse the existing confirmed Auth Owner predicate; no client owner flag or metadata.
 v_owner := coalesce(public.work_review_owner(p_user),false);
 if not v_owner and p_expected_cost is distinct from 8 then return jsonb_build_object('error','COPY_PRICE_CHANGED','cost',8); end if;
 if not v_owner and total<8 then return jsonb_build_object('error','INSUFFICIENT_CREDIT','balance',greatest(total,0),'debt',greatest(-total,0)); end if;
 insert into public.bible_expression_copy_receipts(user_id,source_id,prompt_key,copy_locale,copy_text,delta,reason)
 values(p_user,p_receipt,p_key,p_locale,p_text,case when v_owner then 0 else -8 end,case when v_owner then 'owner_prompt_copy' else 'bible_prompt_copy' end);
 return jsonb_build_object('charged',case when v_owner then 0 else 8 end,'balance',greatest(total-case when v_owner then 0 else 8 end,0),'debt',greatest(-total,0),'text',p_text,'exempt',v_owner);
end;
$$;
revoke all on function public.bible_prompt_copy(uuid,uuid,text,text,text,integer) from public,anon,authenticated;
grant execute on function public.bible_prompt_copy(uuid,uuid,text,text,text,integer) to service_role;

