const returning = new Set<string>(MUSIC_POOL_RETURN_IDS);
const excluded = new Set<string>(MUSIC_POOL_RETURN_EXCLUDED_IDS);
export function isMusicPoolReturnActive(now: number) {
  return now >= MUSIC_POOL_RETURN_START && now < MUSIC_POOL_RETURN_END;
}
export function isMusicPoolReturnExcluded(id: string | undefined, now: number) {
  return isMusicPoolReturnActive(now) && !!id && excluded.has(id);
}
export function isMusicPoolReturnCandidate(id: string | undefined, createdAt: string | null | undefined, now: number) {
  const published = createdAt ? Date.parse(createdAt) : NaN;
  return isMusicPoolReturnActive(now) && !!id && returning.has(id) && !excluded.has(id)
    && Number.isFinite(published) && published < MUSIC_POOL_RETURN_CUTOFF && published <= now;
}
